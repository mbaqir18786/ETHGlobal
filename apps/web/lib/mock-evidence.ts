/**
 * Validates whether an input string is a valid Ethereum address.
 */
export function validateEthereumAddress(address: string): {
  isValid: boolean;
  error?: string;
  normalized?: string;
} {
  const trimmed = address.trim();

  if (!trimmed) {
    return {
      isValid: false,
      error: "Please enter an Ethereum address to begin investigation.",
    };
  }

  if (!trimmed.startsWith("0x")) {
    return {
      isValid: false,
      error: "Invalid format: Address must begin with '0x' prefix.",
    };
  }

  if (trimmed.length !== 42) {
    return {
      isValid: false,
      error: `Invalid length: Ethereum addresses must be exactly 42 characters (including 0x). Current length is ${trimmed.length}.`,
    };
  }

  const hexPattern = /^0x[0-9a-fA-F]{40}$/;
  if (!hexPattern.test(trimmed)) {
    return {
      isValid: false,
      error: "Invalid characters: Address contains non-hexadecimal characters. Valid characters are 0-9 and a-f (case insensitive).",
    };
  }

  return {
    isValid: true,
    normalized: trimmed.toLowerCase(),
  };
}

/**
 * Searches the registry for evidence matching the investigated address.
 * Never labels an address as malicious unless matching evidence exists.
 */
export function searchAddressEvidence(inputAddress: string): AddressInvestigationResult {
  const validation = validateEthereumAddress(inputAddress);

  if (!validation.isValid || !validation.normalized) {
    return {
      address: inputAddress,
      isValid: false,
      searchedAt: new Date().toISOString(),
      hasMatchingEvidence: false,
      totalAssociatedLookalikes: 0,
      evidenceList: [],
    };
  }

  const normalized = validation.normalized;

  const matches = MOCK_EVIDENCE_REGISTRY.filter((rec) => {
    return (
      rec.investigatedAddress.toLowerCase() === normalized ||
      rec.relationship.genuineAddress.toLowerCase() === normalized ||
      rec.relationship.suspectedAddress.toLowerCase() === normalized
    );
  });

  return {
    address: inputAddress.trim(),
    isValid: true,
    searchedAt: new Date().toISOString(),
    hasMatchingEvidence: matches.length > 0,
    totalAssociatedLookalikes: matches.length,
    evidenceList: matches,
  };
}

